#include "aura_switch_wait.h"

bool aura_switch_wait_for_commit(int commit_step, long now, long deadline)
{
    if (commit_step == 0)
        return false;

    /* mismo criterio con signo que TIME_BEFORE(now, deadline) */
    return (now - deadline) < 0;
}
