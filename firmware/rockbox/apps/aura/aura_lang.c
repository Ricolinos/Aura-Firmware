/* D-357: tabla indexada por aura_lang_t (ES/EN/FR/DE/RU/IT, en ese
 * orden -- coincide 1:1 con el enum de aura_settings.h) en vez de la
 * rama ternaria de dos vias que habia antes. */
static const char *const *const strings_by_lang[AURA_LANG_COUNT] = {
    [AURA_LANG_ES] = strings_es,
    [AURA_LANG_EN] = strings_en,
    [AURA_LANG_FR] = strings_fr,
    [AURA_LANG_DE] = strings_de,
    [AURA_LANG_RU] = strings_ru,
    [AURA_LANG_IT] = strings_it,
};

const char *aura_str(aura_str_id_t id)
{
    /* D-345: el cast cubre las dos formas del enum sin warning. gcc
     * elige un tipo sin signo para aura_str_id_t (no tiene valores
     * negativos), asi que `id < 0` era siempre falso y avisaba
     * -Wtype-limits en cada compilacion de este archivo; con un tipo
     * con signo, el cast sigue atrapando cualquier negativo. */
    if ((unsigned)id >= (unsigned)AURA_STR_COUNT)
        return "";

    /* D-357: mismo criterio de cast sin signo para aura_lang_t (D-345). */
    aura_lang_t lang = ((unsigned)aura_settings.language < (unsigned)AURA_LANG_COUNT)
                            ? aura_settings.language : AURA_LANG_ES;
    const char *s = strings_by_lang[lang][id];
    return s ? s : "";
}
